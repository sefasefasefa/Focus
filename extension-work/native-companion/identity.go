package main

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"net"
	"os"
	"os/exec"
	"regexp"
	"runtime"
	"sort"
	"strings"
)

var (
	windowsMachineGUID = regexp.MustCompile(`(?im)^\s*MachineGuid\s+REG_SZ\s+([^\r\n]+)\s*$`)
	macPlatformUUID    = regexp.MustCompile(`"IOPlatformUUID"\s*=\s*"([^"]+)"`)
)

func stableDeviceID() (string, error) {
	machineID, err := readMachineIdentity()
	if err != nil {
		return "", err
	}
	machineID = strings.ToLower(strings.TrimSpace(machineID))
	if len(machineID) < 8 {
		return "", errors.New("machine identifier is missing or too short")
	}

	sum := sha256.Sum256([]byte("rodon-stable-device-v1\x00" + runtime.GOOS + "\x00" + machineID))
	return "rdn1_" + hex.EncodeToString(sum[:]), nil
}

func stableMACAddresses() []string {
	interfaces, err := net.Interfaces()
	if err != nil {
		return []string{}
	}
	return stableMACAddressesFromInterfaces(interfaces)
}

func stableMACAddressesFromInterfaces(interfaces []net.Interface) []string {
	addresses := make([]string, 0, len(interfaces))
	seen := make(map[string]struct{}, len(interfaces))
	for _, iface := range interfaces {
		if iface.Flags&net.FlagLoopback != 0 || len(iface.HardwareAddr) != 6 {
			continue
		}
		// Ignore multicast and locally administered addresses, which are commonly
		// generated by virtual adapters or Wi-Fi MAC randomization.
		if iface.HardwareAddr[0]&0x03 != 0 {
			continue
		}
		isZero := true
		for _, octet := range iface.HardwareAddr {
			if octet != 0 {
				isZero = false
				break
			}
		}
		if isZero {
			continue
		}

		address := strings.ToLower(iface.HardwareAddr.String())
		if _, exists := seen[address]; exists {
			continue
		}
		seen[address] = struct{}{}
		addresses = append(addresses, address)
	}
	sort.Strings(addresses)
	if len(addresses) > 64 {
		addresses = addresses[:64]
	}
	return addresses
}

func readMachineIdentity() (string, error) {
	switch runtime.GOOS {
	case "windows":
		output, err := exec.Command(
			"reg.exe",
			"query",
			`HKLM\SOFTWARE\Microsoft\Cryptography`,
			"/v",
			"MachineGuid",
		).Output()
		if err != nil {
			return "", err
		}
		match := windowsMachineGUID.FindSubmatch(output)
		if len(match) != 2 {
			return "", errors.New("Windows MachineGuid was not found")
		}
		return string(match[1]), nil

	case "darwin":
		output, err := exec.Command(
			"/usr/sbin/ioreg",
			"-rd1",
			"-c",
			"IOPlatformExpertDevice",
		).Output()
		if err != nil {
			return "", err
		}
		match := macPlatformUUID.FindSubmatch(output)
		if len(match) != 2 {
			return "", errors.New("macOS IOPlatformUUID was not found")
		}
		return string(match[1]), nil

	case "linux":
		for _, path := range []string{"/etc/machine-id", "/var/lib/dbus/machine-id"} {
			value, err := os.ReadFile(path)
			if err == nil && strings.TrimSpace(string(value)) != "" {
				return string(value), nil
			}
		}
		return "", errors.New("Linux machine-id was not found")

	default:
		return "", errors.New("unsupported operating system")
	}
}

func runtimePlatform() string {
	return runtime.GOOS + "/" + runtime.GOARCH
}
